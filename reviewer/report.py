"""Plain code: render a checked review as Markdown (PR comment or file) or JSON."""

from __future__ import annotations

import json
from dataclasses import asdict

from reviewer.validate import Review

ICONS = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🔵"}
VERDICT_TEXT = {
    "approve": "✅ Looks good",
    "comment": "💬 Worth a look",
    "request_changes": "⛔ Changes requested",
}
MARKER = "<!-- ai-code-reviewer -->"  # lets a later run find its own comment


def to_markdown(review: Review, meta: dict, skipped: list[tuple[str, str]], reviewed: int) -> str:
    out = [MARKER, f"## AI Code Review: {VERDICT_TEXT[review.verdict]}", "", review.summary, ""]

    counts = [f"{ICONS[s]} {review.count(s)} {s}" for s in ICONS if review.count(s)]
    out.append(f"**{len(review.findings)} finding(s)** across {reviewed} file(s)" + (": " + " · ".join(counts) if counts else ""))
    out.append("")

    if review.findings:
        out += ["### Findings", ""]
        for i, f in enumerate(review.findings, 1):
            where = f"`{f.file}:{f.line}`" + ("" if f.on_changed_line else " (context line)")
            out.append(f"**{i}. {ICONS[f.severity]} {f.title}**  ")
            out.append(f"{where} · {f.severity} · {f.category}")
            out.append("")
            if f.explanation:
                out.append(f.explanation)
                out.append("")
            if f.suggestion:
                out.append(f"> **Suggestion:** {f.suggestion}")
                out.append("")

    if review.suggested_tests:
        out += ["### Suggested tests", ""]
        for t in review.suggested_tests:
            prefix = f"`{t['file']}`: " if t["file"] else ""
            out.append(f"- [ ] {prefix}{t['description']}")
        out.append("")

    checks = []
    if skipped:
        checks.append("Not reviewed: " + ", ".join(f"`{p}` ({why})" for p, why in skipped))
    if review.dropped:
        checks.append(f"Dropped {len(review.dropped)} model finding(s) that failed checks: "
                      + "; ".join(f"{d.get('title', '?')!s} ({why})" for d, why in review.dropped))
    checks += review.notes
    if checks:
        out += ["<details><summary>Review checks</summary>", ""]
        out += [f"- {c}" for c in checks]
        out += ["", "</details>", ""]

    cost = f" · est. ${meta['cost_usd']:.3f}" if meta.get("cost_usd") is not None else ""
    out.append(f"<sub>Generated by ai-code-reviewer with Claude Code ({meta.get('model', 'unknown')}) "
               f"in {meta.get('duration_s', '?')}s{cost}. AI feedback can be wrong; a human decides.</sub>")
    return "\n".join(out) + "\n"


def to_json(review: Review, meta: dict, skipped: list[tuple[str, str]]) -> str:
    data = asdict(review)
    data["dropped"] = [{"finding": d, "reason": why} for d, why in review.dropped]
    data["skipped_files"] = [{"file": p, "reason": why} for p, why in skipped]
    data["meta"] = meta
    return json.dumps(data, indent=2) + "\n"
